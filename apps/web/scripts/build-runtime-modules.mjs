#!/usr/bin/env node

// Generate the browser-side ESM modules that the page exposes to community
// integration bundles via an import map. Community bundles declare `react`,
// `react/jsx-runtime`, `react/jsx-dev-runtime`, `@openmapx/core`, and
// `@openmapx/integration-framework` (+ its `/react` subpath) as external; the
// page's import map (apps/web/src/app/layout.tsx) points those bare imports at
// the files emitted here.
//
// CRITICAL: these files must NOT bundle their own copy of React or the platform
// packages. The Next host bundles its own React; a second React copy in a
// community bundle would render hooks against a different dispatcher ("Invalid
// hook call") and a different `IntegrationRegistryContext` instance (so
// `useIntegrationRegistry()` reads the empty default). Instead each emitted
// module RE-EXPORTS the host's live instance from `globalThis.__OMX_RUNTIME__`,
// which the host populates at startup (apps/web/src/lib/communityRuntime.ts).
// This is the Grafana/Module-Federation "shared singleton" guarantee achieved
// with native ESM + an import map.
//
// To get each module's export names (ESM named exports must be static) we run
// esbuild once per module purely to read its `metafile.outputs[].exports`, then
// emit a re-export stub. The bundle itself is discarded (`write: false`).
//
// Runs in `prebuild` (and `predev`) so the files exist before Next serves
// `apps/web/public/`. Keep the MODULES list in sync with FRONTEND_RUNTIME_EXTERNALS
// in packages/integration-framework/src/installer.ts and the import map in layout.tsx.

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { copyMapLibreRuntimeAssets } from "./maplibre-runtime.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(__dirname, "..");
const outDir = resolve(webRoot, "public/runtime");

mkdirSync(outDir, { recursive: true });
copyMapLibreRuntimeAssets(outDir);

const GLOBAL = "globalThis.__OMX_RUNTIME__";

const MODULES = [
  { id: "react", outfile: "react.js" },
  { id: "react/jsx-runtime", outfile: "react-jsx-runtime.js" },
  { id: "react/jsx-dev-runtime", outfile: "react-jsx-dev-runtime.js" },
  { id: "@openmapx/core", outfile: "openmapx-core.js" },
  { id: "@openmapx/integration-framework", outfile: "openmapx-integration-framework.js" },
  {
    id: "@openmapx/integration-framework/react",
    outfile: "openmapx-integration-framework-react.js",
    external: ["@openmapx/integration-framework"],
  },
  { id: "maplibre-gl", outfile: "maplibre-gl.js" },
];

/**
 * Read a module's ESM export names. Real npm packages (react, react/jsx-*) are
 * introspected directly with `import()` — esbuild's CJS→ESM analysis doesn't
 * statically enumerate React's named exports, but node's interop does. TS-source
 * workspace packages (`@openmapx/*`) can't be imported by node, so fall back to
 * an esbuild metafile probe (the bundle output is discarded).
 */
async function exportNamesOf(mod) {
  try {
    const ns = await import(mod.id);
    const keys = Object.keys(ns);
    if (keys.length > 0) return keys;
  } catch {
    // Not a node-importable module (TS source) — fall through to esbuild.
  }
  const result = await build({
    entryPoints: [mod.id],
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "es2022",
    absWorkingDir: webRoot,
    write: false,
    metafile: true,
    logLevel: "warning",
    define: { "process.env.NODE_ENV": '"production"' },
    external: mod.external ?? [],
    outfile: "__runtime_probe__.js",
  });
  const outputs = result.metafile.outputs;
  const entry = Object.values(outputs).find((o) => o.entryPoint) ?? Object.values(outputs)[0];
  return entry?.exports ?? [];
}

for (const mod of MODULES) {
  const exports = await exportNamesOf(mod);
  const named = exports.filter((n) => n !== "default" && /^[A-Za-z_$][\w$]*$/.test(n));
  const lines = [
    "// Auto-generated by scripts/build-runtime-modules.mjs — do not edit.",
    `const m = ${GLOBAL} && ${GLOBAL}[${JSON.stringify(mod.id)}];`,
    `if (!m) throw new Error(${JSON.stringify(`OpenMapX runtime singleton not initialized: ${mod.id}`)});`,
  ];
  if (named.length > 0) {
    lines.push(`export const { ${named.join(", ")} } = m;`);
  }
  lines.push(exports.includes("default") ? "export default m.default;" : "export default m;");
  writeFileSync(resolve(outDir, mod.outfile), `${lines.join("\n")}\n`);
}

// Emit an importmap.json so any consumer (the page, tools, tests) has a single
// source of truth for which bare specifiers the runtime promises.
const importmap = {
  imports: Object.fromEntries(MODULES.map((m) => [m.id, `/runtime/${m.outfile}`])),
};
writeFileSync(resolve(outDir, "importmap.json"), `${JSON.stringify(importmap, null, 2)}\n`);
