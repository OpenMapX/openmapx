import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { generate } from "@graphql-codegen/cli";
import { createCodegenConfig } from "./codegen.config.mjs";
import { formatSource } from "./format-source.mjs";

export async function generateArtifacts(selectedTargets) {
  const files = await generate(createCodegenConfig(selectedTargets), false);
  return files
    .sort((left, right) => left.filename.localeCompare(right.filename))
    .map(({ filename, content }) => ({
      filename,
      content: formatSource(
        filename,
        `// biome-ignore-all lint: Generated by GraphQL Code Generator; edit operations/*.graphql.\n// Generated by pnpm entur:generate.\n${content}`,
      ),
    }));
}

export async function writeOrCheckArtifacts(files, { check = false } = {}) {
  const stale = [];
  for (const { filename, content } of files) {
    if (!check) {
      await writeFile(filename, content);
      continue;
    }
    try {
      if ((await readFile(filename, "utf8")) !== content) stale.push(`${filename} (stale)`);
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
      stale.push(`${filename} (missing)`);
    }
  }
  if (stale.length) {
    throw new Error(
      `Entur generated output is stale or missing:\n${stale.join("\n")}\nRun pnpm entur:generate.`,
    );
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).some((argument) => argument !== "--check")) {
    console.error("Usage: node scripts/entur/codegen.mjs [--check]");
    process.exitCode = 1;
  } else {
    try {
      await writeOrCheckArtifacts(await generateArtifacts(), {
        check: process.argv.includes("--check"),
      });
    } catch (error) {
      console.error(error.message);
      process.exitCode = 1;
    }
  }
}
