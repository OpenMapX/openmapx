import { resolve } from "node:path";

/** Orval's supported transformer keeps downloads unconsumed, never Blob buffered. */
export function dataManagerResponseTypes(verb, bodylessStatuses = new Set()) {
  const transform = (entry) =>
    bodylessStatuses.has(String(entry.key))
      ? { ...entry, value: "void", schemas: [], isRef: false }
      : entry.contentType &&
          entry.contentType !== "application/json" &&
          entry.contentType !== "application/x-ndjson"
        ? { ...entry, value: "globalThis.Response", schemas: [] }
        : entry;
  return {
    ...verb,
    response: {
      ...verb.response,
      types: {
        ...verb.response.types,
        success: verb.response.types.success.map(transform),
        errors: verb.response.types.errors.map(transform),
      },
    },
  };
}
export function operationIds(document) {
  const ids = [];
  for (const item of Object.values(document.paths ?? {})) {
    for (const [method, operation] of Object.entries(item)) {
      if (!["get", "post", "head", "delete", "put", "patch", "options"].includes(method)) continue;
      if (!operation.operationId || !/^[A-Za-z_$][\w$]*$/.test(operation.operationId))
        throw new Error("Every data-manager operation needs a valid identifier");
      if (ids.includes(operation.operationId))
        throw new Error(`Duplicate operationId: ${operation.operationId}`);
      ids.push(operation.operationId);
    }
  }
  if (!ids.length) throw new Error("No data-manager operations found");
  return ids.sort();
}
export function operationBindings(ids) {
  return `// biome-ignore-all lint: Generated operation bindings.\n// Generated by pnpm data-manager:sdk:generate. Do not edit.\nimport { bindDataManagerOperation, type DataManagerRequestOptions } from "../transport";\n${ids.map((id) => `const ${id}Bound = bindDataManagerOperation(${JSON.stringify(id)});\nexport async function ${id}Request<T>(url: string, options?: DataManagerRequestOptions): Promise<T> { return ${id}Bound<T>(url, options); }`).join("\n")}\n`;
}
export function createCodegenConfig({ inputDocument, outputDirectory }) {
  const operations = Object.fromEntries(
    operationIds(inputDocument).map((id) => [
      id,
      {
        mutator: {
          path: resolve(outputDirectory, "generated/operation-bindings.generated.ts"),
          name: `${id}Request`,
        },
      },
    ]),
  );
  const bodylessByOperation = new Map();
  for (const item of Object.values(inputDocument.paths ?? {})) {
    for (const operation of Object.values(item)) {
      if (!operation?.operationId) continue;
      bodylessByOperation.set(
        operation.operationId,
        new Set(
          Object.entries(operation.responses ?? {})
            .filter(
              ([, response]) => !response.content || Object.keys(response.content).length === 0,
            )
            .map(([status]) => status),
        ),
      );
    }
  }
  return {
    input: { target: inputDocument },
    output: {
      target: resolve(outputDirectory, "generated/data-manager.generated.ts"),
      schemas: resolve(outputDirectory, "generated/models"),
      client: "fetch",
      headers: true,
      urlEncodeParameters: true,
      override: {
        operations,
        transformer: (verb) =>
          dataManagerResponseTypes(verb, bodylessByOperation.get(verb.operationId)),
        header: () =>
          "// biome-ignore-all lint: Generated by Orval; edit data-manager contracts and regenerate.\n// Generated by pnpm data-manager:sdk:generate. Do not edit.\n",
      },
    },
  };
}
