export function operationIds(document) {
  const ids = [];
  for (const item of Object.values(document.paths ?? {})) {
    for (const [method, operation] of Object.entries(item)) {
      if (!["get", "post", "head", "delete", "put", "patch", "options"].includes(method)) continue;
      if (!operation.operationId || !/^[A-Za-z_$][\w$]*$/.test(operation.operationId))
        throw new Error("Every SDK operation needs a valid identifier");
      if (ids.includes(operation.operationId))
        throw new Error(`Duplicate operationId: ${operation.operationId}`);
      ids.push(operation.operationId);
    }
  }
  if (!ids.length) throw new Error("No SDK operations found");
  return ids.sort();
}
export function emitOperationBindings(
  ids,
  { bindFunction, optionsType, transportPath, command, bindFunctions = {} },
) {
  return `// biome-ignore-all lint: Generated operation bindings.\n// Generated by ${command}. Do not edit.\nimport { ${[...new Set([bindFunction, ...Object.values(bindFunctions)])].join(", ")}, type ${optionsType} } from "${transportPath}";\n${ids.map((id) => `const ${id}Bound = ${bindFunctions[id] ?? bindFunction}(${JSON.stringify(id)});\nexport async function ${id}Request<T>(url: string, options?: ${optionsType}): Promise<T> { return ${id}Bound<T>(url, options); }`).join("\n")}\n`;
}
