// biome-ignore-all lint/suspicious/noConsole: Standalone generator script.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * The release's built-in service files, from the repository:
 * `packages/core/src/services/embedded-service-files.bundle.ts` lists every
 * file a built-in mount names (and Traefik's configuration) with a literal
 * `new URL(…)`, so the ops-agent's runtime bundle embeds each one and its
 * digest covers them.
 *
 * It is generated, never edited by hand: `pnpm generate:service-files`.
 * `--check` fails when it is stale.
 */

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MODULE = "packages/core/src/services/embedded-service-files.bundle.ts";
const MANIFEST_MODULE = "packages/core/src/services/embedded-built-in-services.bundle.ts";
const TRAEFIK_RELEASE_PATHS = ["config/traefik.yml", "config/dynamic"];

function git(args, options = {}) {
  return execFileSync("git", args, { cwd: ROOT, maxBuffer: 64 * 1024 * 1024, ...options });
}

/** The release's built-in service IDs, as its bundle embeds their manifests. */
function releaseServiceIds() {
  const source = readFileSync(join(ROOT, MANIFEST_MODULE), "utf8");
  return [...source.matchAll(/"\.\.\/\.\.\/\.\.\/\.\.\/services\/([a-z0-9-]+)\/service\.json"/g)]
    .map((match) => match[1])
    .sort();
}

/** The paths each manifest names in a service directory, as `serviceFileReferences` derives them. */
function references(ids) {
  const paths = new Set();
  for (const id of ids) {
    const manifest = JSON.parse(readFileSync(join(ROOT, "services", id, "service.json"), "utf8"));
    for (const mount of manifest.bindMounts ?? []) {
      const source = mount.source;
      if (source.startsWith("@service:")) {
        const rest = source.slice("@service:".length);
        const colon = rest.indexOf(":");
        if (colon > 0)
          paths.add(`${rest.slice(0, colon)}/${posix.normalize(rest.slice(colon + 1))}`);
        continue;
      }
      if (source.startsWith("@") || source.startsWith("$") || source.startsWith("/")) continue;
      paths.add(`${id}/${posix.normalize(source)}`);
    }
    if (id === "traefik") for (const path of TRAEFIK_RELEASE_PATHS) paths.add(`traefik/${path}`);
  }
  return [...paths].sort();
}

/** The tracked files at each referenced path, with their executable bit. */
export function releaseServiceFiles() {
  const files = new Map();
  for (const reference of references(releaseServiceIds())) {
    const listed = git(["ls-files", "-s", "-z", "--", `services/${reference}`], {
      encoding: "utf8",
    });
    const entries = listed.split("\0").filter(Boolean);
    if (entries.length === 0) throw new Error(`services/${reference} is not in the repository`);
    for (const entry of entries) {
      const [meta, path] = entry.split("\t");
      const [mode] = meta.split(" ");
      const relative = path.slice("services/".length);
      if (relative.split("/").some((part) => part.startsWith("."))) continue;
      const [serviceId, ...rest] = relative.split("/");
      files.set(relative, { serviceId, path: rest.join("/"), executable: mode === "100755" });
    }
  }
  return [...files.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([, file]) => file);
}

export function renderModule(files) {
  const entries = files
    .map(
      (file) =>
        `    {\n      serviceId: ${JSON.stringify(file.serviceId)},\n      path: ${JSON.stringify(file.path)},\n      executable: ${file.executable},\n      url: new URL(${JSON.stringify(`../../../../services/${file.serviceId}/${file.path}`)}, import.meta.url),\n    },`,
    )
    .join("\n");
  return `// Generated by \`pnpm generate:service-files\` (scripts/service-files.mjs); do not edit.
import type { EmbeddedServiceFiles } from "./embedded-service-files";

/**
 * The ops-agent runtime bundle's variant of \`embedded-service-files.ts\`.
 *
 * The bundler copies every literal URL below into the bundle's \`assets/\`, so
 * the bundle digest, which the release build checks, covers each file. Run
 * from source, the URLs name the repository's own files.
 */
export function embeddedBuiltInServiceFiles(): EmbeddedServiceFiles | null {
  return {
    files: [
${entries}
    ],
  };
}
`;
}

/** `text` as the repository's formatter writes `path`, so the files pass its check. */
function formatted(path, text) {
  return execFileSync(
    join(ROOT, "node_modules", ".bin", "biome"),
    ["format", `--stdin-file-path=${path}`],
    {
      cwd: ROOT,
      input: text,
      encoding: "utf8",
    },
  );
}

function main() {
  const files = releaseServiceFiles();
  const module = formatted(MODULE, renderModule(files));
  if (!process.argv.includes("--check")) {
    writeFileSync(join(ROOT, MODULE), module);
    console.log(`${files.length} service files, ${MODULE} written.`);
    return;
  }
  if (readFileSync(join(ROOT, MODULE), "utf8") !== module) {
    console.error(`${MODULE} is stale`);
    console.error("Run `pnpm generate:service-files` and commit the result.");
    process.exit(1);
  }
  console.log(`${files.length} service files: the bundle list is current.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
