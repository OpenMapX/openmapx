import { resolve } from "node:path";
import { emitOperationBindings, operationIds } from "../codegen/operation-bindings.mjs";
import { validatedResponseTypes } from "./validated-response-types.mjs";

const adminFamilies = [
  { key: "accountAdmin", tag: "account-admin", models: "account-models" },
  { key: "dataManagerAdmin", tag: "data-manager-admin", models: "models", required: true },
  {
    key: "activityAdmin",
    tag: "activity-admin",
    models: "activity-models",
    client: activityClient,
  },
  { key: "integrationAdmin", tag: "integration-admin", models: "integration-models" },
  { key: "serviceAdmin", tag: "service-admin", models: "service-models", client: serviceClient },
  { key: "extensionAdmin", tag: "extension-admin", models: "extension-models" },
];
const generatedHeader = () =>
  "// biome-ignore-all lint: Generated by Orval; edit API contracts and regenerate.\n// Generated by pnpm sdk:generate. Do not edit.\n";

function adminFamilyConfig(document, family, outputDirectory) {
  return {
    input: { target: document },
    output: {
      target: resolve(outputDirectory, `generated/admin/${family.tag}.generated.ts`),
      schemas: resolve(outputDirectory, `generated/admin/${family.models}`),
      client: family.client ?? "fetch",
      headers: true,
      urlEncodeParameters: true,
      override: {
        operations: Object.fromEntries(
          operationIds(document).map((id) => [
            id,
            {
              mutator: {
                path: resolve(outputDirectory, "generated/admin/operation-bindings.generated.ts"),
                name: `${id}Request`,
              },
            },
          ]),
        ),
        header: generatedHeader,
      },
    },
  };
}

export function createCodegenConfig({ inputDocument, outputDirectory }) {
  return {
    runtimeMetadata: {
      input: {
        target: selectTaggedDocument(inputDocument, "runtime-metadata"),
        filters: { tags: ["runtime-metadata"] },
      },
      output: {
        target: resolve(outputDirectory, "generated/runtime-metadata.generated.ts"),
        schemas: { path: resolve(outputDirectory, "generated/models"), type: "zod" },
        client: "fetch",
        headers: true,
        schemaFileExtension: ".generated.ts",
        override: {
          transformer: validatedResponseTypes,
          header: generatedHeader,
          mutator: { path: resolve(outputDirectory, "sdk-transport.ts"), name: "sdkRequest" },
          includeZodSchemaInArguments: true,
          fetch: { runtimeValidation: true },
          zod: {
            version: 4,
            generateReusableSchemas: true,
            strict: { body: true, response: true },
          },
        },
      },
    },
    ...Object.fromEntries(
      adminFamilies.flatMap((family) => {
        const document = selectTaggedDocument(inputDocument, family.tag);
        return family.required || Object.keys(document.paths).length
          ? [[family.key, adminFamilyConfig(document, family, outputDirectory)]]
          : [];
      }),
    ),
  };
}

/** Supported Orval custom client: keep Orval URL/parameter code, expose SSE as a target. */
export function activityClient(clients) {
  return {
    ...clients.fetch,
    async client(verb, options, ...rest) {
      if (!isEventStream(verb.originalOperation))
        return clients.fetch.client(verb, options, ...rest);
      const generated = await clients.fetch.client(
        {
          ...verb,
          // Header models retain the HTTP wire contract. Native EventSource owns
          // Last-Event-ID, so its target factory exposes no explicit header argument.
          headers: undefined,
          props: verb.props.filter((prop) => prop.type !== "header"),
          response: {
            ...verb.response,
            definition: { ...verb.response.definition, success: "AdminEventStreamTarget" },
          },
          override: {
            ...verb.override,
            fetch: { ...verb.override.fetch, includeHttpResponseReturnType: false },
          },
        },
        options,
        ...rest,
      );
      return {
        ...generated,
        imports: [
          ...generated.imports,
          { name: "AdminEventStreamTarget", importPath: "../../admin-sdk-transport" },
        ],
      };
    },
  };
}
/** Supported custom client + fetch factory output: private fetch retains Orval's
 * URL/header/query generation. Public plain-text streams require a consumer.
 * Compose YAML and all-error down use the ordinary fetch emitter unchanged.
 */
export function serviceClient(clients) {
  return {
    ...clients.fetch,
    async client(verb, options, ...rest) {
      const byteResponse = isByteResponse(verb.originalOperation);
      const byteRequest =
        !!verb.originalOperation.requestBody?.content?.["application/octet-stream"];
      const textResponse = Object.entries(verb.originalOperation.responses ?? {}).some(
        ([status, response]) => /^2\d\d$/.test(status) && response.content?.["text/plain"],
      );
      if (!byteResponse && !byteRequest && !textResponse)
        return clients.fetch.client(verb, options, ...rest);
      const optionsType = byteResponse
        ? "AdminByteResponseRequestOptions"
        : byteRequest
          ? "AdminBinaryUploadRequestOptions"
          : "AdminTextStreamRequestOptions";
      const generated = await clients.fetch.client(
        {
          ...verb,
          response: byteRequest
            ? verb.response
            : {
                ...verb.response,
                definition: { ...verb.response.definition, success: "undefined" },
                types: {
                  ...verb.response.types,
                  success: verb.response.types.success.map((response) => ({
                    ...response,
                    value: "undefined",
                    isRef: false,
                    imports: [],
                    schemas: [],
                  })),
                },
              },
        },
        {
          ...options,
          context: {
            ...options.context,
            output: {
              ...options.context.output,
              client: "fetch",
              override: {
                ...options.context.output.override,
                fetch: { ...options.context.output.override.fetch, httpClientInjection: "factory" },
              },
            },
          },
        },
        ...rest,
      );
      const name = verb.operationName;
      // Orval operation names are already camel-cased identifiers.
      const urlName = `get${name[0].toUpperCase()}${name.slice(1)}Url`;
      const scope = `${name}Client`;
      const args = `${name}Arguments`;
      return {
        ...generated,
        returnType: undefined,
        implementation: `${generated.returnType()}
const ${scope} = (() => {
${generated.implementation}
return { ${name}, ${urlName} };
})();
export const ${urlName} = ${scope}.${urlName};
type ${args} = Parameters<typeof ${scope}.${name}>;
export const ${name}: (${verb.props.map((prop, index) => `${prop.name}: ${args}[${index}]`).join(", ")}, options${byteRequest ? "?" : ""}: ${optionsType}) => ReturnType<typeof ${scope}.${name}> = ${scope}.${name};
${verb.originalOperation["x-openmapx-native-download"] ? `export const get${name[0].toUpperCase()}${name.slice(1)}Target = (${verb.props.map((prop, index) => `${prop.name}: ${args}[${index}]`).join(", ")}, options?: AdminNativeDownloadTargetOptions): Promise<AdminNativeDownloadTarget> => bindAdminDownloadTarget(${JSON.stringify(verb.operationName)})(${urlName}(${verb.props.map((prop) => prop.name).join(", ")}), options);` : ""}
`,
        imports: [
          ...generated.imports,
          { name: optionsType, importPath: "../../admin-sdk-transport" },
          ...(verb.originalOperation["x-openmapx-native-download"]
            ? [
                {
                  name: "bindAdminDownloadTarget",
                  importPath: "../../admin-sdk-transport",
                  values: true,
                },
                {
                  name: "AdminNativeDownloadTargetOptions",
                  importPath: "../../admin-sdk-transport",
                },
                { name: "AdminNativeDownloadTarget", importPath: "../../admin-sdk-transport" },
              ]
            : []),
        ],
      };
    },
  };
}
function isByteResponse(operation) {
  return Object.entries(operation.responses ?? {}).some(
    ([status, response]) =>
      /^2\d\d$/.test(status) && response.content?.["application/octet-stream"],
  );
}
function isEventStream(operation) {
  return Object.entries(operation.responses ?? {}).some(
    ([status, response]) => /^2\d\d$/.test(status) && response.content?.["text/event-stream"],
  );
}

export function adminOperationBindings(inputDocument) {
  const documents = adminFamilies.map((family) => selectTaggedDocument(inputDocument, family.tag));
  // Merge methods as well as paths: different adopted families may share a path.
  const combined = { paths: {} };
  for (const document of documents)
    for (const [path, item] of Object.entries(document.paths))
      combined.paths[path] = { ...combined.paths[path], ...item };
  const bindFunctions = {};
  const optionsTypes = {};
  for (const item of Object.values(combined.paths))
    for (const operation of Object.values(item)) {
      if (operation?.operationId && isByteResponse(operation)) {
        bindFunctions[operation.operationId] = "bindAdminByteOperation";
        optionsTypes[operation.operationId] = "AdminSdkRequestOptions";
      } else if (
        operation?.operationId &&
        operation.requestBody?.content?.["application/octet-stream"]
      ) {
        bindFunctions[operation.operationId] = "bindAdminBinaryUploadOperation";
        optionsTypes[operation.operationId] = "AdminSdkRequestOptions";
      } else if (operation?.operationId && isEventStream(operation)) {
        bindFunctions[operation.operationId] = "bindAdminStreamOperation";
        optionsTypes[operation.operationId] = "AdminEventStreamTargetOptions";
      }
    }
  return emitOperationBindings(operationIds(combined), {
    bindFunction: "bindAdminOperation",
    bindFunctions,
    optionsTypes,
    optionsType: "AdminSdkRequestOptions",
    transportPath: "../../admin-sdk-transport",
    command: "pnpm sdk:generate",
  });
}

/** Select the adopted family without pulling unrelated schema models into its output. */
export function selectTaggedDocument(document, tag) {
  const paths = {};
  for (const [path, item] of Object.entries(document.paths ?? {})) {
    const operations = Object.fromEntries(
      Object.entries(item).filter(([, operation]) => operation?.tags?.includes(tag)),
    );
    if (Object.keys(operations).length)
      paths[path] = { ...(item.parameters ? { parameters: item.parameters } : {}), ...operations };
  }
  const components = document.components?.securitySchemes
    ? { securitySchemes: document.components.securitySchemes }
    : {};
  const visited = new Set();
  function visit(value) {
    if (!value || typeof value !== "object") return;
    if (typeof value.$ref === "string" && value.$ref.startsWith("#/components/")) {
      const [, , category, name] = value.$ref.split("/");
      if (!category || !name || visited.has(value.$ref)) return;
      visited.add(value.$ref);
      const definition = document.components?.[category]?.[name];
      if (!definition) throw new Error(`Unresolved SDK reference: ${value.$ref}`);
      components[category] ??= {};
      components[category][name] = definition;
      visit(definition);
    }
    for (const child of Object.values(value)) visit(child);
  }
  visit(paths);
  return { ...document, paths, components };
}
