import { resolve } from "node:path";
import { emitOperationBindings, operationIds } from "../codegen/operation-bindings.mjs";
import { validatedResponseTypes } from "./validated-response-types.mjs";

export function createCodegenConfig({ inputDocument, outputDirectory }) {
  const activity = selectTaggedDocument(inputDocument, "activity-admin");
  return {
    runtimeMetadata: {
      input: {
        target: selectTaggedDocument(inputDocument, "runtime-metadata"),
        filters: { tags: ["runtime-metadata"] },
      },
      output: {
        target: resolve(outputDirectory, "generated/runtime-metadata.generated.ts"),
        schemas: { path: resolve(outputDirectory, "generated/models"), type: "zod" },
        client: "fetch",
        headers: true,
        schemaFileExtension: ".generated.ts",
        override: {
          transformer: validatedResponseTypes,
          header: () =>
            "// biome-ignore-all lint: Generated by Orval; edit API contracts and regenerate.\n// Generated by pnpm sdk:generate. Do not edit.\n",
          mutator: { path: resolve(outputDirectory, "sdk-transport.ts"), name: "sdkRequest" },
          includeZodSchemaInArguments: true,
          fetch: { runtimeValidation: true },
          zod: {
            version: 4,
            generateReusableSchemas: true,
            strict: { body: true, response: true },
          },
        },
      },
    },
    dataManagerAdmin: {
      input: { target: selectTaggedDocument(inputDocument, "data-manager-admin") },
      output: {
        target: resolve(outputDirectory, "generated/admin/data-manager-admin.generated.ts"),
        schemas: resolve(outputDirectory, "generated/admin/models"),
        client: "fetch",
        headers: true,
        urlEncodeParameters: true,
        override: {
          operations: Object.fromEntries(
            operationIds(selectTaggedDocument(inputDocument, "data-manager-admin")).map((id) => [
              id,
              {
                mutator: {
                  path: resolve(outputDirectory, "generated/admin/operation-bindings.generated.ts"),
                  name: `${id}Request`,
                },
              },
            ]),
          ),
          header: () =>
            "// biome-ignore-all lint: Generated by Orval; edit API contracts and regenerate.\n// Generated by pnpm sdk:generate. Do not edit.\n",
        },
      },
    },
    ...(Object.keys(activity.paths).length
      ? {
          activityAdmin: {
            input: { target: activity },
            output: {
              target: resolve(outputDirectory, "generated/admin/activity-admin.generated.ts"),
              schemas: resolve(outputDirectory, "generated/admin/activity-models"),
              client: activityClient,
              headers: true,
              urlEncodeParameters: true,
              override: {
                operations: Object.fromEntries(
                  operationIds(activity).map((id) => [
                    id,
                    {
                      mutator: {
                        path: resolve(
                          outputDirectory,
                          "generated/admin/operation-bindings.generated.ts",
                        ),
                        name: `${id}Request`,
                      },
                    },
                  ]),
                ),
                header: () =>
                  "// biome-ignore-all lint: Generated by Orval; edit API contracts and regenerate.\n// Generated by pnpm sdk:generate. Do not edit.\n",
              },
            },
          },
        }
      : {}),
  };
}

/** Supported Orval custom client: keep Orval URL/parameter code, expose SSE as a target. */
export function activityClient(clients) {
  return {
    ...clients.fetch,
    async client(verb, options, ...rest) {
      if (!isEventStream(verb.originalOperation))
        return clients.fetch.client(verb, options, ...rest);
      const generated = await clients.fetch.client(
        {
          ...verb,
          response: {
            ...verb.response,
            definition: { ...verb.response.definition, success: "AdminEventStreamTarget" },
          },
          override: {
            ...verb.override,
            fetch: { ...verb.override.fetch, includeHttpResponseReturnType: false },
          },
        },
        options,
        ...rest,
      );
      return {
        ...generated,
        imports: [
          ...generated.imports,
          { name: "AdminEventStreamTarget", importPath: "../../admin-sdk-transport" },
        ],
      };
    },
  };
}
function isEventStream(operation) {
  return Object.entries(operation.responses ?? {}).some(
    ([status, response]) => /^2\d\d$/.test(status) && response.content?.["text/event-stream"],
  );
}

export function adminOperationBindings(inputDocument) {
  const previous = selectTaggedDocument(inputDocument, "data-manager-admin");
  const activity = selectTaggedDocument(inputDocument, "activity-admin");
  const combined = { paths: { ...previous.paths, ...activity.paths } };
  const bindFunctions = {};
  for (const item of Object.values(activity.paths))
    for (const operation of Object.values(item)) {
      if (operation?.operationId && isEventStream(operation))
        bindFunctions[operation.operationId] = "bindAdminStreamOperation";
    }
  return emitOperationBindings(operationIds(combined), {
    bindFunction: "bindAdminOperation",
    bindFunctions,
    optionsType: "AdminSdkRequestOptions",
    transportPath: "../../admin-sdk-transport",
    command: "pnpm sdk:generate",
  });
}

/** Select the adopted family without pulling unrelated schema models into its output. */
export function selectTaggedDocument(document, tag) {
  const paths = {};
  for (const [path, item] of Object.entries(document.paths ?? {})) {
    const operations = Object.fromEntries(
      Object.entries(item).filter(([, operation]) => operation?.tags?.includes(tag)),
    );
    if (Object.keys(operations).length)
      paths[path] = { ...(item.parameters ? { parameters: item.parameters } : {}), ...operations };
  }
  const components = document.components?.securitySchemes
    ? { securitySchemes: document.components.securitySchemes }
    : {};
  const visited = new Set();
  function visit(value) {
    if (!value || typeof value !== "object") return;
    if (typeof value.$ref === "string" && value.$ref.startsWith("#/components/")) {
      const [, , category, name] = value.$ref.split("/");
      if (!category || !name || visited.has(value.$ref)) return;
      visited.add(value.$ref);
      const definition = document.components?.[category]?.[name];
      if (!definition) throw new Error(`Unresolved SDK reference: ${value.$ref}`);
      components[category] ??= {};
      components[category][name] = definition;
      visit(definition);
    }
    for (const child of Object.values(value)) visit(child);
  }
  visit(paths);
  return { ...document, paths, components };
}
