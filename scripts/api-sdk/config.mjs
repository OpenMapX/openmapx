import { resolve } from "node:path";
import { validatedResponseTypes } from "./validated-response-types.mjs";

export function createCodegenConfig({ inputDocument, outputDirectory }) {
  return {
    runtimeMetadata: {
      input: { target: inputDocument, filters: { tags: ["runtime-metadata"] } },
      output: {
        target: resolve(outputDirectory, "generated/runtime-metadata.generated.ts"),
        schemas: { path: resolve(outputDirectory, "generated/models"), type: "zod" },
        client: "fetch",
        headers: true,
        schemaFileExtension: ".generated.ts",
        override: {
          transformer: validatedResponseTypes,
          header: () =>
            "// biome-ignore-all lint: Generated by Orval; edit API contracts and regenerate.\n// Generated by pnpm sdk:generate. Do not edit.\n",
          mutator: { path: resolve(outputDirectory, "sdk-transport.ts"), name: "sdkRequest" },
          includeZodSchemaInArguments: true,
          fetch: { runtimeValidation: true },
          zod: {
            version: 4,
            generateReusableSchemas: true,
            strict: { body: true, response: true },
          },
        },
      },
    },
  };
}
