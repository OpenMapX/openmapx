import { resolve } from "node:path";

export function createCodegenConfig({ inputDocument, outputDirectory }) {
  const paths = ["/v3/autocomplete", "/v3/reverse", "/v3/place"];
  if (
    Object.keys(inputDocument.paths ?? {}).length !== paths.length ||
    paths.some((path) => {
      const operation = inputDocument.paths?.[path]?.get;
      return (
        operation?.operationId !== path.slice(4) ||
        operation.responses?.[200]?.content?.["application/json"]?.schema?.$ref !==
          "#/components/schemas/Result"
      );
    })
  )
    throw new Error("Unsupported Entur Geocoder operation contract");
  return {
    input: { target: inputDocument },
    output: {
      target: resolve(outputDirectory, "generated/client.ts"),
      schemas: { path: resolve(outputDirectory, "generated/models"), type: "zod" },
      client: "fetch",
      urlEncodeParameters: true,
      override: {
        header: () =>
          "// biome-ignore-all lint: Generated by Orval; edit the pinned Geocoder contract and regenerate.\n// Generated by pnpm entur-geocoder:generate. Do not edit.\n// Upstream schema: EUPL-1.2; see schema/NOTICE.md.\n",
        mutator: { path: resolve(outputDirectory, "transport.ts"), name: "enturGeocoderRequest" },
        includeZodSchemaInArguments: true,
        fetch: { runtimeValidation: true, includeHttpResponseReturnType: false },
        zod: { version: 4, generateReusableSchemas: true },
      },
    },
  };
}
